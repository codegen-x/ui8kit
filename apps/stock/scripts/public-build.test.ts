// The public build of Stock holds no source code of any runtime and no dataset: the detail page shows the live preview, the
// passport and the similar assets only. The per-runtime code and the Dataset are gated features for later (they will be served by
// the service that holds them, with server-side access); a static Vite build cannot hide anything it contains, so the rule is that
// the build never contains them. Builds Stock (STOCK_BASE=/, as on Vercel) into a temporary directory and reads every file.
import { afterAll, beforeAll, describe, expect, test } from "bun:test";
import { mkdtempSync, readdirSync, readFileSync, rmSync, statSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

const APP = join(import.meta.dir, "..");
const REPO = join(APP, "..", "..");
const RUNTIMES = ["svelte", "react", "vue", "solid", "templ", "twig", "latte", "jinja2"] as const;
let out = "";
let files: string[] = [];

const walk = (d: string): string[] => readdirSync(d).flatMap((f) => (statSync(join(d, f)).isDirectory() ? walk(join(d, f)) : [join(d, f)]));

beforeAll(() => {
  out = mkdtempSync(join(tmpdir(), "stock-public-"));
  const r = Bun.spawnSync(["bunx", "vite", "build", "--outDir", out, "--emptyOutDir", "--logLevel", "error"], { cwd: APP, env: { ...process.env, STOCK_BASE: "/" } });
  if (r.exitCode !== 0) throw new Error("vite build failed: " + r.stderr.toString());
  files = walk(out).map((f) => relative(out, f).split("\\").join("/"));
}, 180_000);
afterAll(() => { if (out) rmSync(out, { recursive: true, force: true }); });

/** lines of the generated block sources of a runtime that only source code has: markup, template tags, declarations (>= 32 chars) */
function fingerprints(rt: string): string[] {
  const dir = join(REPO, "packages", "kit-compose", rt, "src", "blocks");
  const lines = walk(dir).sort().flatMap((f) => readFileSync(f, "utf8").split("\n").map((l) => l.trim()))
    .filter((l) => l.length >= 32 && !/^["'`][^"'`]*["'`],?$/.test(l) && !l.startsWith("//") && !l.startsWith("/*") && !l.startsWith("*"));
  const uniq = [...new Set(lines)];
  const step = Math.max(1, Math.floor(uniq.length / 150));
  return uniq.filter((_, i) => i % step === 0);
}

describe("the public build", () => {
  test("serves the page and its assets only: index.html, scripts, styles, fonts", () => {
    expect(files).toContain("index.html");
    expect(files.filter((f) => f !== "index.html" && !/^assets\/[\w.-]+\.(js|css|woff2)$/.test(f))).toEqual([]);
    expect(files.filter((f) => /\.(json|map|svelte|tsx?|jsx|vue|templ|twig|latte|j2|go|py|php)$/i.test(f))).toEqual([]);
    expect(files.filter((f) => /dataset|source|snippet|code/i.test(f))).toEqual([]);
  });

  test("holds no source code of any of the 8 runtimes (sampled lines of every runtime's generated blocks)", () => {
    const text = files.filter((f) => /\.(js|css|html)$/.test(f)).map((f) => readFileSync(join(out, f), "utf8")).join("\n");
    expect(text.length).toBeGreaterThan(100_000);
    for (const marker of ["DO NOT EDIT", "Code generated by", "<script lang=", "{% ", "{{ ", "{block ", "templ ", "package blocks"]) expect(text.includes(marker), marker).toBe(false);
    for (const rt of RUNTIMES) {
      const lines = fingerprints(rt);
      expect(lines.length, rt).toBeGreaterThan(50);
      expect(lines.filter((l) => text.includes(l)), rt).toEqual([]);
    }
  });

  test("the app imports no source text and no other runtime: no ?raw/?url imports, no kit-compose/<rt> but svelte, no emitters", () => {
    const srcs = [...walk(join(APP, "src")), ...walk(join(REPO, "packages", "layouts", "src"))].filter((f) => /\.(ts|svelte)$/.test(f) && !f.endsWith(".test.ts"));
    const bad = srcs.flatMap((f) => [...readFileSync(f, "utf8").matchAll(/(?:from|import)\s*\(?\s*["']([^"']+)["']/g)].map((m) => m[1]!)
      .filter((s) => /\?(raw|url)\b/.test(s) || /kit-compose\/(react|vue|solid|templ|twig|latte|jinja2)\b/.test(s) || /compose-gen\/runtimes|dataset/i.test(s))
      .map((s) => `${relative(REPO, f)}: ${s}`));
    expect(bad).toEqual([]);
  });
});
