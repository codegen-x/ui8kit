// The Go templ package: the bricks as .templ components (typed props structs, recipes embedded as JSON), the Go runtime helpers,
// the LucideIcon asset with its glyph registry, the parity harness (cmd/parity) and the organisms (blocks/).
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { xgenPaths } from "@ui8kit/xgen-schema";
import type { LoadedBrick } from "@ui8kit/xgen-spec";
import type { Inputs } from "@ui8kit/xgen-screens";
import { BANNER, jsonFile, type GeneratedFile } from "@ui8kit/xgen-runtime-core";
import { TemplEmitter, emitGoParityHarness, emitTemplOrganism, presetVar, recipeVar, TEMPL_MODULE, TEMPL_VERSION } from "@ui8kit/xgen-runtime-templ";
import { portableTo } from "@ui8kit/xgen-spec";
import { fileName, indexParts, tierDir, type OrganismSpec } from "@ui8kit/xgen-screens";
import { withSource } from "./source";

export const TEMPL_DIR = "packages/templ/ui";
const ASSETS = join(import.meta.dir, "..", "..", "runtimes", "templ", "assets");
const header = (src: string): string => (src.includes(BANNER) ? src : `// ${BANNER}\n${src}`);

/** the Lucide registry as a Go map literal (tag + attributes per node) */
function lucideGo(xgenRoot: string): string {
  const { icons } = JSON.parse(readFileSync(xgenPaths(xgenRoot).lucide, "utf8")) as { icons: Record<string, Array<[string, Record<string, string>]>> };
  const node = ([tag, attrs]: [string, Record<string, string>]): string =>
    `{${JSON.stringify(tag)}, map[string]string{${Object.entries(attrs).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ")}}}`;
  const rows = Object.entries(icons).map(([name, nodes]) => `\t${JSON.stringify(name)}: {\n${nodes.map((n) => `\t\t${node(n)},`).join("\n")}\n\t},`);
  return [`// ${BANNER}`, `// Lucide icons (ISC license, https://lucide.dev), harvested into xgen/specs/assets/lucide-icons.json.`, ``, `package lucideicon`, ``,
    `type glyphNode struct {\n\tTag   string\n\tAttrs map[string]string\n}`, ``, `var lucide = map[string][]glyphNode{`, ...rows, `}`, ``].join("\n");
}

export function templFiles(bricks: LoadedBrick[], inputs: Inputs, xgenRoot: string, problems: string[] = []): GeneratedFile[] {
  const emitter = new TemplEmitter({ goModule: TEMPL_MODULE });
  const files: GeneratedFile[] = [];
  const spec = (b: LoadedBrick): string => `xgen/specs/ui/${b.specPath.split("/").pop()}`;
  for (const b of bricks) {
    if (b.brick.id === "ui.lucide-icon") {
      files.push({ path: `ui/${b.brick.dir}/lucide-icon.templ`, contents: withSource({ path: "", contents: header(readFileSync(join(ASSETS, "LucideIcon.templ"), "utf8").replaceAll("{{MODULE}}", TEMPL_MODULE)) }, "xgen/runtimes/templ/assets/LucideIcon.templ").contents });
      files.push({ path: `ui/${b.brick.dir}/lucide_icons.go`, contents: withSource({ path: "", contents: lucideGo(xgenRoot) }, "xgen/specs/assets/lucide-icons.json").contents });
      continue;
    }
    for (const f of emitter.emit(b.brick)) {
      if (f.path.endsWith(".json")) files.push({ path: f.path, contents: JSON.stringify({ "//": BANNER, ...JSON.parse(f.contents) }, null, 2) + "\n" });
      else files.push(withSource(f, spec(b)));
    }
  }
  for (const name of readdirSync(join(ASSETS, "go")).filter((n) => n.endsWith(".go")).sort()) {
    files.push(withSource({ path: `utils/${name}`, contents: header(readFileSync(join(ASSETS, "go", name), "utf8")) }, `xgen/runtimes/templ/assets/go/${name}`));
  }
  files.push(...organismFiles(bricks, inputs, problems));
  files.push(withSource(emitGoParityHarness(bricks.map((b) => b.brick), TEMPL_MODULE), "xgen/runtimes/templ/src/go-harness.ts"));
  files.push({ path: "go.mod", contents: `// ${BANNER}\n// Source: xgen/generator/src/templ.ts\nmodule ${TEMPL_MODULE}\n\ngo 1.26.0\n\nrequire github.com/a-h/templ ${TEMPL_VERSION}\n` });
  files.push({ path: ".gitignore", contents: `# ${BANNER}\n# templ generate output: rebuilt by bun run check (templ generate, go vet, go build)\n*_templ.go\n` });
  const parts = bricks.reduce((n, b) => n + b.brick.parts.length, 0);
  files.push(jsonFile("package.json", {
    name: "@ui8kit/templ-ui", version: "0.0.0", private: true,
    description: `Go templ primitives (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs. Go module ${TEMPL_MODULE}; run templ generate before go build.`,
    // one Go package holds every organism, so the block-root zone lists the files the TypeScript packages keep in src/blocks plus their frame components
    ui8kit: { runtime: "templ", generated: true, kit: ["ui", "utils"], composition: ["blocks"], blockRoot: inputs.organisms.map((o) => o.value).filter((o) => tierDir(o.id) === "blocks" || (o.frame && tierDir(o.id) === "components")).map((o) => `blocks/${fileName(o.name)}.templ`).filter((p) => files.some((f) => f.path === p)).sort() },
  }));
  files.push({ path: "README.md", contents: [`<!-- ${BANNER} -->`, `# ${TEMPL_MODULE}`, ``,
    `Go [templ](https://templ.guide) package **generated** by xgen from \`xgen/specs\`: ${bricks.length} bricks, ${parts} parts.`, ``,
    "Every file here starts with `Code generated by xgen. DO NOT EDIT.` Change the spec in `xgen/specs` and run `bun run build`.", ``,
    "```sh", "templ generate && go vet ./... && go build ./...", "```", ``,
    "```go", `import "${TEMPL_MODULE}/ui/button"`, ``, `@button.Button(button.ButtonProps{Variant: "outline"}) { Save }`, "```", ``,
    "The classes are the same Tailwind v4 utilities as the Svelte, React and Vue packages: import their `styles/index.css` (theme and kit) in the app CSS and add `@source` for this folder.", ``].join("\n") });
  return files;
}

/** the organisms portable to the static runtimes, with the recipes and presets they read embedded next to them */
function organismFiles(bricks: LoadedBrick[], inputs: Inputs, problems: string[]): GeneratedFile[] {
  const parts = indexParts(bricks);
  const organisms = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const deps = { parts, organisms, goModule: TEMPL_MODULE };
  const files: GeneratedFile[] = [];
  const recipes = new Set<string>(), presets = new Set<string>();
  for (const o of inputs.organisms) {
    const org = o.value as OrganismSpec;
    if (portableTo(org.portable, "svelte") !== true) continue;
    try {
      const out = emitTemplOrganism(org, deps);
      files.push(withSource(out.file, o.file.slice(o.file.indexOf("xgen/"))));
      out.recipes.forEach((r) => recipes.add(r));
      out.presets.forEach((p) => presets.add(p));
    } catch (e) { problems.push(`templ: ${(e as Error).message}`); }
  }
  const embeds: string[] = [];
  for (const file of [...recipes].sort()) {
    const r = inputs.recipes.find((x) => x.name === file);
    if (!r) { problems.push(`templ: recipe ${file} not found`); continue; }
    files.push({ path: `blocks/recipes/${file}.variants.json`, contents: JSON.stringify({ "//": BANNER, ...(r.value as object) }, null, 2) + "\n" });
    embeds.push(`//go:embed recipes/${file}.variants.json`, `var ${recipeVar(file)}JSON []byte`, `var ${recipeVar(file)} = uiutils.MustRecipe(${recipeVar(file)}JSON)`, ``);
  }
  for (const name of [...presets].sort()) {
    const p = inputs.presets.find((x) => x.value.name === name);
    if (!p) { problems.push(`templ: preset ${name} not found`); continue; }
    files.push({ path: `blocks/presets/${name}.json`, contents: JSON.stringify({ "//": BANNER, ...(p.value as object) }, null, 2) + "\n" });
    embeds.push(`//go:embed presets/${name}.json`, `var ${presetVar(name)}JSON []byte`, `var ${presetVar(name)} = uiutils.Get(uiutils.MustJSON(${presetVar(name)}JSON), "values")`, ``);
  }
  const names = files.filter((f) => f.path.startsWith("blocks/") && f.path.endsWith(".templ")).map((f) => /templ (\w+)\(p \w+Props\)/.exec(f.contents)![1]!).sort();
  files.push({ path: "cmd/parity-blocks/main.go", contents: [`// ${BANNER}`, `// Source: xgen/generator/src/templ.ts`, ``,
    `// Command parity-blocks renders organisms from JSON props: stdin [{"name":"HeroSection","props":{...}}], stdout the HTML of each.`,
    `package main`, ``, `import (`, `\t"bufio"`, `\t"context"`, `\t"encoding/json"`, `\t"fmt"`, `\t"os"`, `\t"strings"`, ``, `\t"github.com/a-h/templ"`, ``, `\t"${TEMPL_MODULE}/blocks"`, `)`, ``,
    `type request struct {\n\tName  string          \`json:"name"\`\n\tProps json.RawMessage \`json:"props"\`\n}`, ``,
    `func component(name string, props []byte) (templ.Component, error) {`, `\tswitch name {`,
    ...names.flatMap((n) => [`\tcase ${JSON.stringify(n)}:`, `\t\tvar p blocks.${n}Props`, `\t\tif err := json.Unmarshal(props, &p); err != nil {`, `\t\t\treturn nil, err`, `\t\t}`, `\t\treturn blocks.${n}(p), nil`]),
    `\t}`, `\treturn nil, fmt.Errorf("unknown organism %s", name)`, `}`, ``,
    `func main() {`, `\tvar reqs []request`, `\tif err := json.NewDecoder(bufio.NewReader(os.Stdin)).Decode(&reqs); err != nil {`, `\t\tpanic(err)`, `\t}`,
    `\tout := make([]string, len(reqs))`, `\tfor i, r := range reqs {`, `\t\tc, err := component(r.Name, r.Props)`, `\t\tif err != nil {`, `\t\t\tout[i] = "ERROR: " + err.Error()`, `\t\t\tcontinue`, `\t\t}`,
    `\t\tvar b strings.Builder`, `\t\tif err := c.Render(context.Background(), &b); err != nil {`, `\t\t\tout[i] = "ERROR: " + err.Error()`, `\t\t\tcontinue`, `\t\t}`, `\t\tout[i] = b.String()`, `\t}`,
    `\t_ = json.NewEncoder(os.Stdout).Encode(out)`, `}`, ``].join("\n") });
  files.push({ path: "blocks/embed.go", contents: [`// ${BANNER}`, `// Source: xgen/generator/src/templ.ts`, ``, `package blocks`, ``, `import (`, `\t_ "embed"`, ``, `\tuiutils "${TEMPL_MODULE}/utils"`, `)`, ``, ...embeds].join("\n") });
  return files;
}
