// The Twig package: the bricks as include templates (one per part, recipes next to them), the PHP runtime (the ui_*
// functions: the Go helpers ported), the LucideIcon asset with its glyph registry, the organisms (blocks/), a parity
// harness (bin/parity.php) and composer.json requiring twig/twig. The emitters print through a Jinja-family dialect,
// so a Jinja2 package can reuse them.
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { xgenPaths } from "@ui8kit/xgen-schema";
import type { LoadedBrick } from "@ui8kit/xgen-spec";
import { portableTo } from "@ui8kit/xgen-spec";
import type { Inputs, OrganismSpec } from "@ui8kit/xgen-screens";
import { fileName, indexParts, tierDir } from "@ui8kit/xgen-screens";
import { BANNER, jsonFile, type GeneratedFile } from "@ui8kit/xgen-runtime-core";
import { emitTwigBrick, emitTwigOrganism, header, twig, TWIG_PACKAGE, TWIG_VERSION } from "@ui8kit/xgen-runtime-twig";

export const TWIG_DIR = "packages/twig/ui";
const ASSETS = join(import.meta.dir, "..", "..", "runtimes", "twig", "assets");
const asset = (name: string): string => readFileSync(join(ASSETS, name), "utf8");
/** a PHP file with the banner after the open tag */
const php = (src: string, source: string): string => src.replace(/^<\?php\n/, `<?php\n\n// ${BANNER}\n// Source: ${source}\n`);
const json = (path: string, value: unknown): GeneratedFile => ({ path, contents: JSON.stringify({ "//": BANNER, ...(value as object) }, null, 2) + "\n" });

export function twigFiles(bricks: LoadedBrick[], inputs: Inputs, xgenRoot: string, problems: string[] = []): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  for (const b of bricks) {
    const source = `xgen/specs/ui/${b.specPath.split("/").pop()}`;
    if (b.brick.id === "ui.lucide-icon") {
      files.push({ path: `ui/${b.brick.dir}/lucide-icon${twig.ext}`, contents: `${header(twig, "xgen/runtimes/twig/assets/lucide-icon.html.twig", "LucideIcon (asset).")}\n${asset("lucide-icon.html.twig")}` });
      const { "//": note, ...icons } = JSON.parse(readFileSync(xgenPaths(xgenRoot).lucide, "utf8")) as Record<string, unknown>;
      files.push(json(`ui/${b.brick.dir}/lucide-icons.json`, { source: note, ...icons }));
      continue;
    }
    try { files.push(...emitTwigBrick(b.brick, source)); } catch (e) { problems.push(`twig: ${(e as Error).message}`); }
  }
  for (const name of readdirSync(join(ASSETS, "php")).filter((n) => n.endsWith(".php")).sort()) {
    files.push({ path: `php/${name}`, contents: php(asset(`php/${name}`), `xgen/runtimes/twig/assets/php/${name}`) });
  }
  files.push({ path: "bin/parity.php", contents: php(asset("parity.php"), "xgen/runtimes/twig/assets/parity.php") });
  files.push(...organismFiles(bricks, inputs, problems));
  const parts = bricks.reduce((n, b) => n + b.brick.parts.length, 0);
  files.push({ path: "composer.json", contents: JSON.stringify({
    name: TWIG_PACKAGE, description: `Twig templates of ui8kit (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs. ${BANNER}`,
    type: "library", license: "MIT", require: { php: ">=8.2", "twig/twig": TWIG_VERSION }, autoload: { "psr-4": { "UI8Kit\\Twig\\": "php/" } },
  }, null, 2) + "\n" });
  files.push({ path: ".gitignore", contents: `# ${BANNER}\n# composer install output: rebuilt by bun run check\nvendor/\ncomposer.lock\n` });
  files.push(jsonFile("package.json", {
    name: "@ui8kit/twig-ui", version: "0.0.0", private: true,
    description: `Twig templates (${bricks.length} bricks, ${parts} parts) generated by xgen from xgen/specs; PHP runtime in php/ (composer package ${TWIG_PACKAGE}).`,
    // the organisms share one folder, so the block-root zone lists the files the TypeScript packages keep in src/blocks plus their frame components
    ui8kit: { runtime: "twig", generated: true, kit: ["ui", "php"], composition: ["blocks"], blockRoot: inputs.organisms.map((o) => o.value).filter((o) => tierDir(o.id) === "blocks" || (o.frame && tierDir(o.id) === "components")).map((o) => `blocks/${fileName(o.name)}${twig.ext}`).filter((p) => files.some((f) => f.path === p)).sort() },
  }));
  files.push({ path: "README.md", contents: [`<!-- ${BANNER} -->`, `# ${TWIG_PACKAGE}`, ``,
    `[Twig](https://twig.symfony.com) templates **generated** by xgen from \`xgen/specs\`: ${bricks.length} bricks, ${parts} parts, and the blocks.`, ``,
    "Every file here starts with `Code generated by xgen. DO NOT EDIT.` Change the spec in `xgen/specs` and run `bun run build`.", ``,
    "```php", `$twig = \\UI8Kit\\Twig\\Extension::environment('/path/to/packages/twig/ui');`, `echo $twig->render('ui/button/button.html.twig', ['p' => ['Variant' => 'outline'], 'children' => 'Save']);`, "```", ``,
    "In a template: `{{ include('ui/button/button.html.twig', {p: {Variant: 'outline'}, children: label}, with_context = false) }}`. Brick props use the canonical",
    "names (`Variant`, `Class`, `Attrs`), block props the JSON names of the TypeScript props (`title`, `className`); `children` is markup.", ``,
    "The classes are the same Tailwind v4 utilities as the Svelte, React, Vue and Solid packages: import their `styles/index.css` in the app CSS and add `@source` for this folder.", ``].join("\n") });
  return files.sort((a, b) => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0));
}

/** the organisms portable to the static runtimes, with the recipes and presets they read copied next to them */
function organismFiles(bricks: LoadedBrick[], inputs: Inputs, problems: string[]): GeneratedFile[] {
  const organisms = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const deps = { parts: indexParts(bricks), organisms, recipePath: (f: string) => `blocks/recipes/${f}.variants.json`, presetPath: (n: string) => `blocks/presets/${n}.json` };
  const files: GeneratedFile[] = [];
  const recipes = new Set<string>(), presets = new Set<string>();
  for (const o of inputs.organisms) {
    const org = o.value as OrganismSpec;
    if (portableTo(org.portable, "svelte") !== true) continue;
    try {
      const out = emitTwigOrganism(org, deps, o.file.slice(o.file.indexOf("xgen/")));
      files.push(...out.files);
      out.recipes.forEach((r) => recipes.add(r));
      out.presets.forEach((p) => presets.add(p));
    } catch (e) { problems.push(`twig: ${(e as Error).message}`); }
  }
  for (const file of [...recipes].sort()) {
    const r = inputs.recipes.find((x) => x.name === file);
    if (!r) problems.push(`twig: recipe ${file} not found`);
    else files.push(json(deps.recipePath(file), r.value));
  }
  for (const name of [...presets].sort()) {
    const p = inputs.presets.find((x) => x.value.name === name);
    if (!p) problems.push(`twig: preset ${name} not found`);
    else files.push(json(deps.presetPath(name), p.value));
  }
  return files;
}
