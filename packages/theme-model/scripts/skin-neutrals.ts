// Writes src/skin-neutrals.ts: the lightness (and the alpha, where a skin has one) of every neutral token (palette.ts NEUTRAL_TOKENS) of every skin, light and dark, read
// from the skin CSS of the kit (packages/shared/app/src/styles/skins/<id>.css, hsl() values; the first block is light, the second
// dark); `bun run skin-neutrals`. A custom palette tints these tokens with its own hue and keeps the skin's lightness, so the root
// style needs no DOM and the numbers are fixed at build time (as taste-data's skin-colors.ts).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SKIN_IDS } from "@ui8kit/taste-data/taste";
import { NEUTRAL_TOKENS } from "../src/neutral-tokens";

const DIR = join(import.meta.dir, "../../shared/app/src/styles/skins");
const OUT = join(import.meta.dir, "../src/skin-neutrals.ts");

const round1 = (n: number) => Math.round(n * 10) / 10;
/** [lightness] or [lightness, alpha] of a token (the kit's own dark theme draws its lines in translucent white) */
function value(css: string, name: string, nth: 0 | 1, skin: string): string {
  const all = [...css.matchAll(new RegExp(`--${name}:\\s*hsl\\(\\s*[\\d.]+\\s+[\\d.]+%\\s+([\\d.]+)%\\s*(?:/\\s*([\\d.]+)(%?))?\\s*\\)`, "g"))];
  const m = all[nth];
  if (all.length !== 2 || !m) throw new Error(`${skin}: --${name} needs one light and one dark hsl() value, found ${all.length}`);
  const l = round1(Number(m[1]));
  if (m[2] === undefined) return `[${l}]`;
  const a = m[3] ? Number(m[2]) / 100 : Number(m[2]);
  return `[${l}, ${Math.round(a * 100) / 100}]`;
}

/** the text of src/skin-neutrals.ts from the skin CSS now (the test compares it with the file, so the table cannot drift) */
export function build(): string {
const rows = ["default", ...SKIN_IDS].map((id) => {
  const css = readFileSync(join(DIR, `${id}.css`), "utf8");
  const mode = (nth: 0 | 1) => `[${NEUTRAL_TOKENS.map((t) => value(css, t, nth, id)).join(", ")}]`;
  return `  "${id}": { light: ${mode(0)}, dark: ${mode(1)} },`;
});
return `// Generated by scripts/skin-neutrals.ts from the skin CSS of the kit (\`bun run skin-neutrals\`). Do not edit by hand.
// The neutral tokens of every skin in the order of NEUTRAL_TOKENS (neutral-tokens.ts): [lightness %] or [lightness %, alpha];
// "default" is the kit's own theme (no skin).
export type Neutral = readonly [number] | readonly [number, number];
export const SKIN_NEUTRALS: Record<string, { light: readonly Neutral[]; dark: readonly Neutral[] }> = {
${rows.join("\n")}
};
`;
}
export const OUT_FILE = OUT;
if (import.meta.main) { writeFileSync(OUT, build()); console.log(`skin-neutrals: ${["default", ...SKIN_IDS].length} skins x ${NEUTRAL_TOKENS.length} tokens -> ${OUT}`); }
