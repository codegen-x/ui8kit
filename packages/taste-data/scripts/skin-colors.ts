// Writes src/skin-colors.ts: --primary, --background and --accent of every skin, light and dark, as OKLab (L, a, b).
// Read from the skin CSS of the kit (packages/shared/app/src/styles/skins/<id>.css, hsl() values); `bun run skin-colors`.
// The recommender ranks skins by distance in this table, so it needs no DOM and the numbers are fixed at build time.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { SKIN_IDS } from "../src/taste";

const DIR = join(import.meta.dir, "../../shared/app/src/styles/skins");
const OUT = join(import.meta.dir, "../src/skin-colors.ts");

function hslToRgb(h: number, s: number, l: number): [number, number, number] {
  s /= 100; l /= 100;
  const k = (n: number) => (n + h / 30) % 12;
  const a = s * Math.min(l, 1 - l);
  const f = (n: number) => l - a * Math.max(-1, Math.min(k(n) - 3, Math.min(9 - k(n), 1)));
  return [f(0), f(8), f(4)];
}
const lin = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
function oklab([r, g, b]: [number, number, number]): [number, number, number] {
  const [R, G, B] = [lin(r), lin(g), lin(b)];
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B);
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B);
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B);
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s];
}
const round = (n: number) => Math.round(n * 1e4) / 1e4;

function token(block: string, name: string): [number, number, number] {
  const m = new RegExp(`--${name}:\\s*hsl\\(\\s*([\\d.]+)\\s+([\\d.]+)%\\s+([\\d.]+)%`).exec(block);
  if (!m) throw new Error(`no --${name} hsl() in block`);
  return oklab(hslToRgb(Number(m[1]), Number(m[2]), Number(m[3]))).map(round) as [number, number, number];
}

/** the body of the first rule whose selector line matches */
function rule(css: string, selector: RegExp): string {
  const lines = css.split("\n");
  const at = lines.findIndex((l) => selector.test(l) && l.trimEnd().endsWith("{"));
  if (at < 0) throw new Error(`no rule ${selector}`);
  const out: string[] = [];
  for (let i = at + 1; i < lines.length && !lines[i]!.startsWith("}"); i++) out.push(lines[i]!);
  return out.join("\n");
}

const rows: string[] = [];
for (const id of SKIN_IDS) {
  const css = readFileSync(join(DIR, `${id}.css`), "utf8");
  const light = rule(css, new RegExp(`^(?::root)?\\[data-skin="${id}"\\] \\{`));
  const dark = rule(css, new RegExp(`^(?::root)?\\[data-skin="${id}"\\]:is\\(\\.dark`));
  const t = (b: string) => `{ primary: [${token(b, "primary")}], background: [${token(b, "background")}], accent: [${token(b, "accent")}] }`;
  rows.push(`  "${id}": { light: ${t(light)}, dark: ${t(dark)} },`);
}
writeFileSync(OUT, `// Generated by scripts/skin-colors.ts from the skin CSS of the kit (\`bun run skin-colors\`). Do not edit by hand.
// --primary, --background and --accent of every skin in each theme, as OKLab [L, a, b].
import type { SkinId } from "./taste";

export type Lab = readonly [number, number, number];
export type SkinPalette = { primary: Lab; background: Lab; accent: Lab };

export const SKIN_COLORS: Record<SkinId, { light: SkinPalette; dark: SkinPalette }> = {
${rows.join("\n")}
};
`);
console.log(`wrote ${SKIN_IDS.length} skins to src/skin-colors.ts`);
