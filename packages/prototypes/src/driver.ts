// The driver of packages/prototypes: reads the blocks of the simple line (BlockSpec.line) from packages/compose-gen, projects their
// clean organisms onto prototypes (project.ts: wireframes, rectangles only), and writes out/:
//   svelte/{blocks,shapes,index.ts}                the wireframes (Svelte 5) and their shapes; they import only svelte and the kit
//                                                  (@ui8kit/kit/ui/box/Box.svelte, cn from @ui8kit/kit/utils): no clean block, no
//                                                  composition, no recipe ships (the clean blocks are the registry's)
//   contracts/<item>/1.json, contracts/v0.json     what a builder reads (contract.ts)
//   models/<id>@<v>.schema.json, <id>@<v>.ts, validate.ts   the content models: JSON Schema 2020-12, types, validate()
//   manifest.json                                  sha256 of every file above and of the inputs (no timestamps, no commit:
//                                                  the consumer pins the commit in its own lock, see ui8kit/prototypes codegen.lock.json)
// usage: bun packages/prototypes/src/driver.ts [--check]
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadInputs, partsFromKit, ROOT, svelteOrganism, validateOrganism, type OrganismSpec } from "../../compose-gen";
import { fileName } from "../../compose-gen/screens/src/index";
import type { BlockSpec } from "../../compose-gen/screens/src/ir";
import { contentType, loadModels, schemaOf, typesOf } from "../../compose-gen/model/src/index";
import { contractIndex, contractOf, type Contract } from "./contract";
import { ALIGN, CONTAINER, JUSTIFY, PADDING, project } from "./project";
import { ROLE, shapes } from "./shapes";

export const PKG = path.resolve(import.meta.dir, "..");
export const OUT = path.join(PKG, "out");
const HEAD = "Code generated by packages/prototypes/src/driver.ts from packages/compose-gen/specs. DO NOT EDIT.";
function fail(msg: string): never { throw new Error(`prototypes: ${msg}`); }
const sha = (s: string): string => createHash("sha256").update(s).digest("hex");
const banner = (file: string, body: string): string => {
  const b = body.replace(/^<!-- Code generated by compose-gen\. DO NOT EDIT\. -->\n/, "").replace(/^\/\/ Code generated by compose-gen\. DO NOT EDIT\.\n/, "");
  return file.endsWith(".svelte") ? `<!-- ${HEAD} -->\n${b}` : `// ${HEAD}\n${b}`;
};

export interface Built { files: Map<string, string>; contracts: Contract[]; organisms: OrganismSpec[] }

export function build(): Built {
  const inputs = loadInputs(ROOT);
  const parts = partsFromKit();
  const byName = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const recipes = Object.fromEntries(inputs.recipes.map((x) => [x.name, x.value]));
  const presets = inputs.presets.map((p) => p.value);
  const models = loadModels(ROOT);
  const dict = inputs.dictionary.value as { blocks: { variants: Record<string, Record<string, string>> } };
  const blocks = inputs.blocks.map((b) => b.value as BlockSpec).filter((b) => b.line === "simple").sort((a, b) => a.id.localeCompare(b.id));

  const protos: OrganismSpec[] = [], contracts: Contract[] = [];
  for (const b of blocks) {
    const clean = byName[b.organism]!, model = models.get(b.model!)!.model;
    const p = project(clean, b, model);
    protos.push(p.organism);
    contracts.push(contractOf(b, clean, model, p.places, dict.blocks.variants[b.id.slice("block.".length)] ?? {}));
  }
  const ours = [...protos, ...shapes];
  const all = { ...byName, ...Object.fromEntries(ours.map((o) => [o.name, o])) };
  const problems = ours.flatMap((o) => validateOrganism(o, parts, all, recipes as never, presets as never).map((e) => `${o.name}: ${e}`));
  if (problems.length) throw new Error(`prototypes: invalid views:\n${problems.join("\n")}`);

  const files = new Map<string, string>();
  const shapeFiles = new Set(shapes.map((o) => fileName(o.name)));
  // the shapes live in shapes/, the kit Box and cn come from the kit the consumer installs
  const relocate = (s: string): string => s
    .replace(/(["'])\.\.\/components\/([a-z0-9-]+)(\.svelte|\.types)?\1/g, (m, q: string, f: string, ext = "") => (shapeFiles.has(f) ? `${q}../shapes/${f}${ext}${q}` : m))
    .replace(/(["'])@kit\/box\/Box\.svelte\1/g, "$1@ui8kit/kit/ui/box/Box.svelte$1")
    .replace(/import \{ cn \} from "\.\.\/utils";/g, `import { cn } from "@ui8kit/kit/utils";`);
  const deps = { parts, organisms: all, partPath: (n: string) => (n === "Box" ? "@kit/box/Box.svelte" : fail(`a wireframe uses ${n}, only Box`)), recipes };
  for (const o of ours) for (const f of svelteOrganism(o, deps as never)) {
    const rel = f.path.replace(/^components\//, "shapes/");
    files.set(`svelte/${rel}`, banner(rel, relocate(f.contents)));
  }
  // a wireframe imports svelte and the kit, nothing else (no clean block, composition or recipe ships)
  for (const [f, body] of files) for (const m of body.matchAll(/(?:from|import)\s+["']([^"']+)["']/g)) {
    const spec = m[1]!;
    if (!(spec === "svelte" || spec === "@ui8kit/kit/ui/box/Box.svelte" || spec === "@ui8kit/kit/utils" || /^\.\.?\/(shapes|blocks)\/[a-z0-9-]+(\.svelte|\.types)?$/.test(spec) || /^\.\/[a-z0-9-]+(\.svelte|\.types)?$/.test(spec)))
      fail(`${f} imports ${spec}: a wireframe imports only svelte and @ui8kit/kit (Box, cn)`);
  }
  const blockExports = protos.flatMap((o) => [`export { default as ${o.name} } from "./blocks/${fileName(o.name)}.svelte";`, `export type { ${o.name}Props } from "./blocks/${fileName(o.name)}.svelte";`]);
  const shapeExports = shapes.map((o) => `export { default as ${o.name} } from "./shapes/${fileName(o.name)}.svelte";`);
  files.set("svelte/index.ts", `// ${HEAD}\n// The wireframes of the simple line (rectangles only) and their shapes.\n${[...blockExports, ...shapeExports].join("\n")}\n`);

  // the class strings a consumer's hand-written layer must share with the wireframes (ui8kit/prototypes classes.ts): one source
  files.set("classes.json", json({ roles: ROLE, align: ALIGN, justify: JUSTIFY, padding: PADDING, container: CONTAINER }));
  for (const c of contracts) files.set(`contracts/${c.item}/${c.version}.json`, json(c));
  files.set("contracts/v0.json", json(contractIndex(contracts)));
  const validateSrc = readFileSync(path.join(ROOT, "model/src/validate.ts"), "utf8");
  files.set("models/validate.ts", `// ${HEAD}\n// Copied from packages/compose-gen/model/src/validate.ts.\n${validateSrc}`);
  for (const [key, { model }] of [...models].sort(([a], [b]) => a.localeCompare(b))) {
    files.set(`models/${key}.schema.json`, json(schemaOf(model)));
    const { $schema: _s, ...spec } = model;
    files.set(`models/${key}.ts`, [`// ${HEAD}`, `// The content model ${key} (packages/compose-gen/specs/models/${model.id}.json): types, the model and validate().`,
      `import { validate, type Issue, type ModelSpec } from "./validate";`, ``, typesOf(model), ``,
      `export const model = ${JSON.stringify(spec, null, 2)} as const satisfies ModelSpec;`, ``,
      `/** the problems of a ${contentType(model)} value (empty: valid) */`, `export const validate${contentType(model)} = (value: unknown): Issue[] => validate(model, value);`, ``].join("\n"));
  }
  const inputsDigest = sha([...blocks.map((b) => JSON.stringify(b)), ...ours.map((o) => JSON.stringify(o)), ...[...models.values()].map((m) => JSON.stringify(m.model))].join("\n"));
  const sorted = [...files.keys()].sort();
  files.set("manifest.json", json({
    generator: "codegen-x/ui8kit packages/prototypes", version: 2, runtime: "svelte", kit: "@ui8kit/kit", modes: ["wireframe"],
    items: contracts.map((c) => ({ item: c.item, block: c.block, model: c.model, contract: `contracts/${c.item}/${c.version}.json`, svelte: `svelte/blocks/${c.item}.svelte` })),
    inputs: { sha256: inputsDigest },
    files: Object.fromEntries(sorted.map((f) => [f, sha(files.get(f)!)])),
  }));
  return { files, contracts, organisms: ours };
}

const json = (v: unknown): string => `${JSON.stringify(v, null, 2)}\n`;

function onDisk(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { recursive: true, withFileTypes: true }).filter((e) => e.isFile()).map((e) => path.relative(dir, path.join(e.parentPath, e.name)).split(path.sep).join("/"));
}

/** the files of out/ that differ from the build, or are stale */
export function drift(b = build()): string[] {
  const bad: string[] = [];
  for (const [rel, body] of b.files) { const p = path.join(OUT, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(rel); }
  for (const f of onDisk(OUT)) if (!b.files.has(f)) bad.push(`${f} (stale)`);
  return bad;
}

if (import.meta.main) {
  const b = build();
  if (process.argv.includes("--check")) {
    const bad = drift(b);
    if (bad.length) { console.error(`prototypes: out/ is out of date (bun packages/prototypes/src/driver.ts):\n  ${bad.slice(0, 20).join("\n  ")}`); process.exit(1); }
    console.log(`prototypes: ${b.contracts.length} prototypes, ${b.files.size} files in out/ up to date`);
  } else {
    rmSync(OUT, { recursive: true, force: true });
    for (const [rel, body] of b.files) { const p = path.join(OUT, rel); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, body); }
    console.log(`prototypes: wrote ${b.files.size} files (${b.contracts.map((c) => c.item).join(", ")})`);
  }
}
