// Prototype: React organism emitter on kit-compose. xgen organism specs (xgen/specs/organisms/<id>.json: view tree of
// bricks, slots, text, when/then/else, each/do, op cn) -> react/src/organisms/<id>.tsx importing ../compose (never the kit
// directly, never raw tags). Brick props PascalCase -> composition props camelCase (Class -> className); LucideIcon Name -> inline
// Lucide SVG. bun src/organisms.ts [--check]. Only the ids in PROTOTYPE are emitted for now.
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BRICKS } from "./map";
import { LUCIDE, MANUAL } from "./manual";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SPECS = path.resolve(root, "../../xgen/specs/organisms");
export const PROTOTYPE = ["article-block", "footer-sitemap", "post-tags"];
const HEAD = "Code generated by packages/kit-compose/src/organisms.ts from xgen/specs/organisms. DO NOT EDIT.";
/** Lucide icons the organisms use beyond src/manual.ts (lucide.dev path data) */
const ICONS: Record<string, string> = { ...LUCIDE,
  "arrow-right": LUCIDE.x.replace(/<path[^]*<\/svg>/, `<path d="M5 12h14"></path><path d="m12 5 7 7-7 7"></path></svg>`) };
const ICON_SIZE: Record<string, string> = { "12": "size-3", "16": "size-4", "20": "size-5", "24": "size-6" };

type Expr = { $: string } | { op: string; args: Expr[] } | string | number | boolean;
type Node = Record<string, any>;
type Ctx = { used: Set<string>; locals: Set<string>; props: Set<string> };

const camel = (k: string) => k === "Class" ? "className" : k[0].toLowerCase() + k.slice(1);
const ref = (p: string, c: Ctx) => { const [h, ...t] = p.split("."); return c.locals.has(h) || c.props.has(h) || h === "className" ? [h, ...t].join("?.") : (() => { throw new Error(`organisms: unknown $${p}`); })(); };
function expr(e: Expr, c: Ctx): string {
  if (typeof e !== "object") return JSON.stringify(e);
  if ("$" in e) return ref(e.$, c);
  if (e.op === "cn") { c.used.add("cn"); return `cn(${e.args.map((a) => expr(a, c)).join(", ")})`; }
  throw new Error(`organisms: op ${e.op} not in the prototype`);
}
const attr = (k: string, v: Expr, c: Ctx) => typeof v === "string" ? ` ${k}=${JSON.stringify(v)}` : ` ${k}={${expr(v, c)}}`;
const jsx = (s: string) => s.replace(/stroke-(width|linecap|linejoin)=/g, (_, k: string) => `stroke${k[0].toUpperCase()}${k.slice(1)}=`);

function node(n: Node, c: Ctx): string {
  if (n.slot) return n.slot === "children" ? "{children}" : `{${n.slot}}`;
  if ("text" in n) return `{${expr(n.text, c)}}`;
  if (n.when) return `{${expr(n.when, c)} ? (<>${n.then.map((x: Node) => node(x, c)).join("")}</>) : ${n.else ? `(<>${n.else.map((x: Node) => node(x, c)).join("")}</>)` : "null"}}`;
  if (n.each) {
    const inner: Ctx = { ...c, locals: new Set([...c.locals, n.as]) };
    const kids = n.do.map((x: Node) => node(x, inner));
    const key = n.key ? expr(n.key, inner) : "i";
    return `{(${expr(n.each, c)} ?? []).map((${n.as}${n.key ? "" : ", i"}) => (<Fragment key={${key}}>${kids.join("")}</Fragment>))}`;
  }
  if (n.use) {
    const use = n.use as string;
    if (!BRICKS[use] && !MANUAL.includes(use)) throw new Error(`organisms: brick ${use} has no composition`);
    c.used.add(use);
    const props = { ...(n.props ?? {}) } as Record<string, Expr>;
    let kids = (n.children ?? []).map((x: Node) => node(x, c)).join("");
    if (use === "LucideIcon") {
      const name = props.Name as string, size = props.Size; delete props.Name; delete props.Size;
      if (typeof name !== "string" || !ICONS[name]) throw new Error(`organisms: Lucide icon ${String(name)} not in the prototype`);
      const sz = ICON_SIZE[String(size ?? "16")];
      props.Class = props.Class ? { op: "cn", args: [sz, props.Class] } : sz;
      kids = jsx(ICONS[name]);
    }
    const a = Object.entries(props).map(([k, v]) => attr(camel(k), v, c)).join("") + Object.entries(n.attrs ?? {}).map(([k, v]) => attr(k, v as Expr, c)).join("");
    return kids ? `<${use}${a}>${kids}</${use}>` : `<${use}${a} />`;
  }
  throw new Error(`organisms: node ${JSON.stringify(n).slice(0, 80)} not in the prototype`);
}

const tsType = (t: any) => typeof t === "string" ? (t === "string" ? "string" : t === "boolean" ? "boolean" : t === "number" ? "number" : "unknown") : t.ts ?? "unknown";

export function emit(id: string): string {
  const s = JSON.parse(readFileSync(path.join(SPECS, `${id}.json`), "utf8"));
  const props = new Set<string>((s.props ?? []).map((p: any) => p.name));
  const c: Ctx = { used: new Set(), locals: new Set(), props };
  const body = s.view.map((n: Node) => node(n, c)).join("");
  const uses = JSON.stringify(s.view);
  const hasChildren = uses.includes('"slot":"children"');
  const usesFragment = body.includes("<Fragment");
  const types = (s.props ?? []).map((p: any) => `  ${p.docs ? `/** ${p.docs} */\n  ` : ""}${p.name}${p.required ? "" : "?"}: ${tsType(p.type)};`);
  const tsRefs = [...new Set(JSON.stringify(s.props).match(/\b(NavLink)\b/g) ?? [])];
  const comps = [...c.used].filter((u) => u !== "cn").sort();
  const defaults = (s.props ?? []).filter((p: any) => p.default !== undefined).map((p: any) => `${p.name} = ${JSON.stringify(p.default)}`);
  const destr = [...(s.props ?? []).map((p: any) => defaults.find((d: string) => d.startsWith(`${p.name} =`)) ?? p.name), ...(body.includes("className") ? ["className"] : []), ...(hasChildren ? ["children"] : [])];
  return `// ${HEAD}
// Source: xgen/specs/organisms/${id}.json${s.docs ? `\n/** ${s.docs} */` : ""}
${hasChildren || usesFragment ? `import { ${[...(usesFragment ? ["Fragment"] : []), ...(hasChildren ? ["type ReactNode"] : [])].join(", ")} } from "react";\n` : ""}import { ${comps.join(", ")} } from "../compose";
${c.used.has("cn") ? `import { cn } from "../../../../kit/react/src/utils";\n` : ""}${tsRefs.length ? `import type { ${tsRefs.join(", ")} } from "./types";\n` : ""}
export type ${s.name}Props = {
${[...types, "  className?: string;", ...(hasChildren ? ["  children?: ReactNode;"] : [])].join("\n")}
};

export function ${s.name}({ ${destr.join(", ")} }: ${s.name}Props) {
  return (<>${body}</>);
}
`;
}

const TYPES = `// ${HEAD}
// Record types of the organisms (from xgen/screens/src/authoring/blocks/navigation.ts).
export type NavLink = { id: string; name: string; icon: string; href?: string };
`;

export function files(): Map<string, string> {
  const out = new Map<string, string>();
  out.set("react/src/organisms/types.ts", TYPES);
  for (const id of PROTOTYPE) out.set(`react/src/organisms/${id}.tsx`, emit(id));
  const names = PROTOTYPE.map((id) => JSON.parse(readFileSync(path.join(SPECS, `${id}.json`), "utf8")).name as string);
  out.set("react/src/organisms/index.ts", `// ${HEAD}\n${PROTOTYPE.map((id) => `export * from "./${id}";`).join("\n")}\nexport type { NavLink } from "./types";\n// ${names.join(", ")}\n`);
  return out;
}

if (import.meta.main) {
  const fs = files(), bad: string[] = [];
  const dir = path.join(root, "react/src/organisms");
  if (process.argv.includes("--check")) {
    for (const [rel, body] of fs) { const p = path.join(root, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(rel); }
    if (existsSync(dir)) for (const f of readdirSync(dir)) if (!fs.has(`react/src/organisms/${f}`)) bad.push(`react/src/organisms/${f} (stale)`);
    if (bad.length) { console.error(`organisms: out of date (bun src/organisms.ts):\n  ${bad.join("\n  ")}`); process.exit(1); }
    console.log(`organisms: ${PROTOTYPE.length} React organisms up to date`);
  } else {
    mkdirSync(dir, { recursive: true });
    for (const [rel, body] of fs) writeFileSync(path.join(root, rel), body);
    console.log(`organisms: wrote ${fs.size} files`);
  }
}
