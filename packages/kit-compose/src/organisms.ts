// Organisms on kit-compose: every organism spec of xgen (xgen/specs/{organisms,parts,patterns}) through the xgen organism emitters
// of Svelte, React, Vue and Solid, with the bricks resolved to the kit-compose compositions (../compose, same API as the former
// bricks) instead of the legacy packages/<runtime>/ui primitives. Per runtime: <runtime>/src/{blocks,components} (the organisms
// and their record types), presets/ (frame geometry read by the `preset` op), utils/ (the expression helpers: tpl, fmtMoney,
// variants, ...), icons/ (LucideIcon by name inside the Icon primitive + the glyph registry; svg is on the raw allowlist). bun src/organisms.ts [--check]
import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { loadSpecs, portableTo } from "@ui8kit/xgen-spec";
import { loadInputs, indexParts, tierDir, fileName, type OrganismSpec } from "@ui8kit/xgen-screens";
import { emitPreset, type GeneratedFile } from "@ui8kit/xgen-runtime-core";
import { emitOrganism as reactOrganism } from "@ui8kit/xgen-runtime-react";
import { emitOrganism as svelteOrganism } from "@ui8kit/xgen-runtime-svelte";
import { emitOrganism as vueOrganism } from "@ui8kit/xgen-runtime-vue";
import { emitOrganism as solidOrganism } from "@ui8kit/xgen-runtime-solid";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const XGEN = path.resolve(root, "../../xgen");
export const JS_RUNTIMES = ["react", "svelte", "vue", "solid"] as const;
export type JsRuntime = (typeof JS_RUNTIMES)[number];
const HEAD = "Code generated by packages/kit-compose/src/organisms.ts from xgen/specs (xgen organism emitters on kit-compose). DO NOT EDIT.";
const OUT_DIRS = ["blocks", "components", "presets", "utils", "icons"];
const EMIT = { react: reactOrganism, svelte: svelteOrganism, vue: vueOrganism, solid: solidOrganism } as const;
const EXT = { react: "tsx", svelte: "svelte", vue: "vue", solid: "tsx" } as const;
const ICON_ASSET = { react: "LucideIcon.tsx", svelte: "LucideIcon.svelte", vue: "LucideIcon.vue", solid: "LucideIcon.tsx" } as const;

function banner(file: string, src: string): string {
  const body = src.replace(/^\/\/ Code generated by xgen\. DO NOT EDIT\.\n/, "").replace(/^<!-- Code generated by xgen\. DO NOT EDIT\. -->\n/, "");
  return file.endsWith(".svelte") || file.endsWith(".vue") ? `<!-- ${HEAD} -->\n${body}` : `// ${HEAD}\n${body}`;
}

export function loadOrganisms() {
  const specs = loadSpecs(XGEN);
  const inputs = loadInputs(XGEN);
  if (specs.problems.length) throw new Error(`organisms: xgen specs: ${specs.problems.join("; ")}`);
  const organisms = inputs.organisms.map((o) => o.value as OrganismSpec).filter((o) => JS_RUNTIMES.every((r) => portableTo(o.portable, r) === true));
  return { specs, inputs, organisms };
}

function lucideRegistry(): string {
  const { icons } = JSON.parse(readFileSync(path.join(XGEN, "specs/assets/lucide-icons.json"), "utf8")) as { icons: Record<string, unknown> };
  return [`// ${HEAD}`, `// Lucide icons (ISC license, https://lucide.dev), from xgen/specs/assets/lucide-icons.json.`,
    `export const LUCIDE: Record<string, Array<[string, Record<string, string>]>> = {`,
    ...Object.entries(icons).map(([n, v]) => `  ${JSON.stringify(n)}: ${JSON.stringify(v)},`), `};`, ``].join("\n");
}

export function runtimeFiles(r: JsRuntime, loaded = loadOrganisms()): Map<string, string> {
  const { specs, inputs, organisms } = loaded;
  const out = new Map<string, string>();
  const parts = indexParts(specs.bricks);
  const recipes = Object.fromEntries(inputs.recipes.map((x) => [x.name, x.value]));
  const jsx = r === "react" || r === "solid";
  const partPath = (n: string) =>
    n === "LucideIcon" ? `../icons/LucideIcon${jsx ? "" : `.${EXT[r]}`}` : jsx ? "../compose" : `../compose/${n}.${EXT[r]}`;
  const deps = { parts, organisms: Object.fromEntries(organisms.map((o) => [o.name, o])), partPath, recipes };
  const barrel: string[] = [];
  for (const o of organisms) {
    for (const f of EMIT[r](o, deps as never)) out.set(`${r}/src/${f.path}`, banner(f.path, f.contents));
    const dir = tierDir(o.id);
    barrel.push(jsx ? `export * from "./${dir}/${fileName(o.name)}";` : `export { default as ${o.name} } from "./${dir}/${fileName(o.name)}.${EXT[r]}";`);
    if (Object.keys(o.records).length) barrel.push(`export type * from "./${dir}/${fileName(o.name)}.types";`);
  }
  for (const p of inputs.presets) {
    const f = emitPreset(p.value, `xgen/screens/src/authoring/presets/${path.basename(p.file, ".json")}.ts`);
    out.set(`${r}/src/${f.path}`, banner(f.path, f.contents.replace(/^\/\/ Code generated by xgen\. DO NOT EDIT\.\n/, "")));
  }
  const utils = path.join(XGEN, "runtimes/core/assets/ts");
  const walk = (rel: string): string[] => readdirSync(path.join(utils, rel), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? walk(path.join(rel, e.name)) : [path.join(rel, e.name)]));
  for (const f of walk("")) out.set(`${r}/src/utils/${f}`, banner(f, readFileSync(path.join(utils, f), "utf8")));
  // owned by kit-compose: the glyph inside the Icon primitive (the LucideIcon composition)
  const icon = readFileSync(path.join(root, `src/assets/${r}/${ICON_ASSET[r]}`), "utf8");
  out.set(`${r}/src/icons/${ICON_ASSET[r]}`, banner(ICON_ASSET[r], icon));
  out.set(`${r}/src/icons/lucide-icons.ts`, lucideRegistry());
  out.set(`${r}/src/organisms.ts`, `// ${HEAD}\n${barrel.join("\n")}\n`);
  return out;
}

export function files(): Map<string, string> {
  const loaded = loadOrganisms(), out = new Map<string, string>();
  for (const r of JS_RUNTIMES) for (const [k, v] of runtimeFiles(r, loaded)) out.set(k, v);
  return out;
}

if (import.meta.main) {
  const fs = files(), bad: string[] = [];
  const owned = (r: string) => [...OUT_DIRS.map((d) => path.join(root, r, "src", d))];
  const onDisk = (dir: string): string[] => existsSync(dir) ? readdirSync(dir, { recursive: true, withFileTypes: true }).filter((e) => e.isFile()).map((e) => path.relative(root, path.join(e.parentPath, e.name))) : [];
  if (process.argv.includes("--check")) {
    for (const [rel, body] of fs) { const p = path.join(root, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(rel); }
    for (const r of JS_RUNTIMES) for (const d of owned(r)) for (const f of onDisk(d)) if (!fs.has(f)) bad.push(`${f} (stale)`);
    if (bad.length) { console.error(`organisms: out of date (bun src/organisms.ts):\n  ${bad.slice(0, 20).join("\n  ")}`); process.exit(1); }
    console.log(`organisms: ${loadOrganisms().organisms.length} organisms x ${JS_RUNTIMES.length} runtimes up to date`);
  } else {
    for (const r of JS_RUNTIMES) for (const d of owned(r)) rmSync(d, { recursive: true, force: true });
    for (const [rel, body] of fs) { const p = path.join(root, rel); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, body); }
    console.log(`organisms: wrote ${fs.size} files (${loadOrganisms().organisms.length} organisms x ${JS_RUNTIMES.length} runtimes)`);
  }
}
