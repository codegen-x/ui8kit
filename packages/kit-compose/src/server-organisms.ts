// Organisms on kit-compose for the server runtimes: every organism spec through the compose-gen dialect emitters, calling the
// kit-compose server compositions (compose/*) over the installed kit primitives (ui/*). Output per runtime:
// <rt>/src/blocks (organism templates, their slot fills, the recipes and presets they read), <rt>/src/icons (the LucideIcon
// glyph inside the Icon primitive), the og_* helpers. `bun src/server-organisms.ts [--check]`.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT as GEN, type OrganismSpec } from "../../compose-gen";
import { emitTemplOrganism, presetVar, recipeVar, type ComposeTarget } from "../../compose-gen/runtimes/templ/src/organism";
import { emitTwigOrganism, jinja, twig, latte, type Dialect } from "../../compose-gen/runtimes/twig/src/index";
import type { PartRef } from "../../compose-gen/runtimes/core/src/index";
import { loadOrganisms } from "./organisms";
import { BRICKS } from "./map";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEAD = "Code generated by packages/kit-compose/src/server-organisms.ts from packages/compose-gen/specs (compose-gen organism emitters on kit-compose). DO NOT EDIT.";
export const SERVER_ORG_RT = ["jinja2", "twig", "latte", "templ"] as const;
export const TEMPL_MODULE = "github.com/codegen-x/ui8kit/packages/kit-compose/templ";
const KIT_MODULE = "github.com/ui8kit/codegen/generated/templ";
export type ServerOrgRuntime = (typeof SERVER_ORG_RT)[number];
const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const DIALECT: Record<Exclude<ServerOrgRuntime, "templ">, Dialect> = { jinja2: jinja, twig, latte };
/** a brick with nothing to add to its primitive (no recipe, classes or tag: SelectOption, OptGroup) has no server composition */
const bare = (name: string) => { const m = BRICKS[name]!; return !(m.recipe || m.extra || m.tag || m.tagFrom); };
const PART: Record<Exclude<ServerOrgRuntime, "templ">, (ref: PartRef) => string> = {
  jinja2: (ref) => {
    const n = ref.part.name;
    if (n === "LucideIcon") return "icons/lucide-icon.html.j2";
    if (bare(n)) return `ui/${kebab(BRICKS[n]!.primitive).split("-")[0]}/${kebab(BRICKS[n]!.primitive)}.html.j2`;
    return `compose/${kebab(n)}.html.j2`;
  },
  twig: (ref) => pascalPath(ref, ".html.twig"),
  latte: (ref) => pascalPath(ref, ".latte"),
};
function pascalPath(ref: PartRef, ext: string): string {
  const n = ref.part.name;
  if (n === "LucideIcon") return `icons/LucideIcon${ext}`;
  if (bare(n)) { const p = BRICKS[n]!.primitive; return `ui/${kebab(p).split("-")[0]}/${p}${ext}`; }
  return `compose/${n}${ext}`;
}
/** Twig and Latte compositions take flat parameters (the camelCase names of the primitive, the recipe keys), not `p` */
function flatCall(template: string, props: Array<[string, string]>, children: string | null, d: Dialect, ref: PartRef): string {
  const param = (k: string) => {
    const p = ref.part.props.find((x) => x.name === k) as { param?: string } | undefined;
    if (!p?.param) throw new Error(`${ref.part.name}: prop ${k} has no server parameter`);
    return p.param;
  };
  const vars: Array<[string, string]> = props.map(([k, v]) => [param(k), v]);
  if (children) vars.push(["children", d.name === "latte" ? `(string) ${children}` : children]);
  return d.include(template, d.hash(vars));
}
const CALL: Record<Exclude<ServerOrgRuntime, "templ">, typeof flatCall | undefined> = { jinja2: undefined, twig: flatCall, latte: flatCall };

const json = (v: unknown) => JSON.stringify({ "//": HEAD, ...(v as object) }, null, 2) + "\n";
const comment = (d: Dialect, src: string) => src.replace(/^\{#- Code generated by compose-gen\. DO NOT EDIT\.\n/, `{#- ${HEAD}\n`).replace(/^\{\* Code generated by compose-gen\. DO NOT EDIT\.\n/, `{* ${HEAD}\n`);

function walk(dir: string, rel = ""): string[] {
  return readdirSync(path.join(dir, rel), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))
    .flatMap((e) => (e.isDirectory() ? (e.name === "__pycache__" ? [] : walk(dir, path.join(rel, e.name))) : [path.join(rel, e.name)]));
}

/** the kit templ package of a primitive: its folder, package name and Props type (read from the installed kit) */
function kitPkg(prim: string): { dir: string; pkg: string } {
  const dir = prim.startsWith("Select") ? "select" : prim === "Summary" ? "disclosure" : prim.toLowerCase();
  const src = readFileSync(path.join(root, "../kit/templ/src/ui", dir, `${dir}.templ`), "utf8");
  return { dir, pkg: src.match(/^package (\w+)/m)![1]! };
}
function templTarget(part: string): ComposeTarget {
  if (part === "LucideIcon") return { pkg: "icons", path: `${TEMPL_MODULE}/src/icons`, fn: "LucideIcon" };
  const prim = BRICKS[part]!.primitive, k = kitPkg(prim);
  if (bare(part)) return { pkg: k.pkg, path: `${KIT_MODULE}/ui/${k.dir}`, fn: prim };
  return { pkg: "compose", path: `${TEMPL_MODULE}/src/compose`, fn: part, embed: { pkg: k.pkg, path: `${KIT_MODULE}/ui/${k.dir}`, type: `${prim}Props` } };
}

function templFiles(loaded: ReturnType<typeof loadOrganisms>): Map<string, string> {
  const { parts, inputs, organisms } = loaded, out = new Map<string, string>(), problems: string[] = [];
  const byName = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const deps = { parts, organisms: byName, goModule: `${TEMPL_MODULE}/src`, utilsPath: `${TEMPL_MODULE}/src/orgutils`, compose: templTarget };
  const recipes = new Set<string>(), presets = new Set<string>();
  for (const o of organisms) {
    const file = inputs.organisms.find((x) => x.value.name === o.name)!.file;
    try {
      const e = emitTemplOrganism(o, deps as never);
      const src = `// Source: ${path.relative(path.resolve(GEN, "../.."), file)}`;
      out.set(`templ/src/${e.file.path}`, e.file.contents.replace(/^\/\/ Code generated by compose-gen\. DO NOT EDIT\.\n/, `// ${HEAD}\n${src}\n`));
      e.recipes.forEach((x) => recipes.add(x)); e.presets.forEach((x) => presets.add(x));
    } catch (err) { problems.push(`${o.name}: ${(err as Error).message}`); }
  }
  if (problems.length) throw new Error(`server organisms (templ):\n${problems.join("\n")}`);
  const embeds: string[] = [];
  for (const n of [...recipes].sort()) {
    out.set(`templ/src/blocks/recipes/${n}.variants.json`, json(inputs.recipes.find((x) => x.name === n)!.value));
    embeds.push(`//go:embed recipes/${n}.variants.json`, `var ${recipeVar(n)}JSON []byte`, `var ${recipeVar(n)} = uiutils.MustRecipe(${recipeVar(n)}JSON)`, ``);
  }
  for (const n of [...presets].sort()) {
    out.set(`templ/src/blocks/presets/${n}.json`, json(inputs.presets.find((x) => x.value.name === n)!.value));
    embeds.push(`//go:embed presets/${n}.json`, `var ${presetVar(n)}JSON []byte`, `var ${presetVar(n)} = uiutils.Get(uiutils.MustJSON(${presetVar(n)}JSON), "values")`, ``);
  }
  out.set("templ/src/blocks/embed.go", [`// ${HEAD}`, ``, `package blocks`, ``, `import (`, `\t_ "embed"`, ``, `\tuiutils "${TEMPL_MODULE}/src/orgutils"`, `)`, ``, ...embeds].join("\n"));
  const go = path.join(GEN, "runtimes/templ/assets/go");
  for (const f of readdirSync(go).filter((f) => f.endsWith(".go") && !f.endsWith("_test.go")).sort())
    out.set(`templ/src/orgutils/${f}`, `// ${HEAD}\n\n${readFileSync(path.join(go, f), "utf8")}`);
  out.set("templ/src/icons/lucide-icon.templ", `// ${HEAD}\n${readFileSync(path.join(root, "src/assets/templ/lucide-icon.templ"), "utf8")}`);
  const { icons } = JSON.parse(readFileSync(path.join(GEN, "specs/assets/lucide-icons.json"), "utf8")) as { icons: Record<string, Array<[string, Record<string, string>]>> };
  const node = ([tag, attrs]: [string, Record<string, string>]) => `{${JSON.stringify(tag)}, map[string]string{${Object.entries(attrs).map(([k, v]) => `${JSON.stringify(k)}: ${JSON.stringify(v)}`).join(", ")}}}`;
  out.set("templ/src/icons/lucide_icons.go", [`// ${HEAD}`, `// Lucide icons (ISC license, https://lucide.dev), from packages/compose-gen/specs/assets/lucide-icons.json.`, ``, `package icons`, ``,
    `type glyphNode struct {\n\tTag   string\n\tAttrs map[string]string\n}`, ``, `var lucide = map[string][]glyphNode{`,
    ...Object.entries(icons).map(([n, nodes]) => `\t${JSON.stringify(n)}: {\n${nodes.map((x) => `\t\t${node(x)},`).join("\n")}\n\t},`), `}`, ``].join("\n"));
  return out;
}

export function serverOrganismFiles(r: ServerOrgRuntime, loaded = loadOrganisms()): Map<string, string> {
  if (r === "templ") return templFiles(loaded);
  const { parts, inputs, organisms } = loaded;
  const d = DIALECT[r], out = new Map<string, string>(), problems: string[] = [];
  const byName = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const deps = {
    parts, organisms: byName, partTemplate: PART[r], callPart: CALL[r],
    recipePath: (f: string) => `blocks/recipes/${f}.variants.json`, presetPath: (n: string) => `blocks/presets/${n}.json`,
  };
  const recipes = new Set<string>(), presets = new Set<string>();
  for (const o of organisms) {
    const file = inputs.organisms.find((x) => x.value.name === o.name)!.file;
    try {
      const e = emitTwigOrganism(o, deps as never, path.relative(path.resolve(GEN, "../.."), file), d);
      for (const f of e.files) out.set(`${r}/src/${f.path}`, comment(d, f.contents));
      e.recipes.forEach((x) => recipes.add(x)); e.presets.forEach((x) => presets.add(x));
    } catch (err) { problems.push(`${o.name}: ${(err as Error).message}`); }
  }
  if (problems.length) throw new Error(`server organisms (${r}):\n${problems.join("\n")}`);
  for (const n of [...recipes].sort()) out.set(`${r}/src/${deps.recipePath(n)}`, json(inputs.recipes.find((x) => x.name === n)!.value));
  for (const n of [...presets].sort()) out.set(`${r}/src/${deps.presetPath(n)}`, json(inputs.presets.find((x) => x.value.name === n)!.value));
  const { icons } = JSON.parse(readFileSync(path.join(GEN, "specs/assets/lucide-icons.json"), "utf8")) as { icons: unknown };
  out.set(`${r}/src/icons/lucide-icons.json`, json({ icons }));
  if (r === "twig" || r === "latte") {
    const ext = r === "twig" ? ".html.twig" : ".latte", ns = r === "twig" ? "Twig" : "Latte";
    out.set(`${r}/src/icons/LucideIcon${ext}`, readFileSync(path.join(root, `src/assets/${r}/LucideIcon${ext}`), "utf8").replace(/^(\{#- |\{\* )/, (m) => `${m}${HEAD}\n    `));
    const php = (f: string) => `<?php\n\n// ${HEAD}\n${readFileSync(f, "utf8").replace(/^<\?php\n/, "").replaceAll("{{RUNTIME}}", ns)}`;
    out.set(`${r}/src/organisms/OrganismExtension.php`, php(path.join(GEN, `runtimes/${r}/assets/php/Extension.php`)));
    for (const f of ["Runtime.php", "CnMerge.php"]) out.set(`${r}/src/organisms/${f}`, php(path.join(GEN, "runtimes/twig/assets/php-shared", f)));
  }
  if (r === "jinja2") {
    out.set(`${r}/src/icons/lucide-icon.html.j2`, readFileSync(path.join(root, "src/assets/jinja2/lucide-icon.html.j2"), "utf8").replace(/^\{#- /, `{#- ${HEAD}\n    `));
    const py = path.join(GEN, "runtimes/jinja2/assets/py/compose_organisms");
    for (const f of walk(py)) out.set(`${r}/src/compose_organisms/${f}`, `# ${HEAD}\n${readFileSync(path.join(py, f), "utf8")}`);
  }
  return out;
}

/** the generated folders, cleared on write so a dropped organism leaves no file behind */
const OWNED = ["src/blocks", "src/icons", "src/compose_organisms", "src/organisms", "src/orgutils"];

if (import.meta.main) {
  const check = process.argv.includes("--check"), bad: string[] = [];
  const loaded = loadOrganisms();
  for (const r of SERVER_ORG_RT) {
    const files = serverOrganismFiles(r, loaded);
    if (check) {
      for (const [rel, body] of files) { const p = path.join(root, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(rel); }
      for (const o of OWNED) { const dir = path.join(root, r, o); if (existsSync(dir)) for (const f of walk(dir)) if (!files.has(path.join(r, o, f))) bad.push(`${path.join(r, o, f)} (stale)`); }
    } else {
      for (const o of OWNED) rmSync(path.join(root, r, o), { recursive: true, force: true });
      for (const [rel, body] of files) { const p = path.join(root, rel); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, body); }
    }
    console.log(`server organisms: ${r}: ${loaded.organisms.length} organisms, ${files.size} files`);
  }
  if (bad.length) { console.error(`server organisms out of date:\n${bad.slice(0, 20).join("\n")}`); process.exit(1); }
}
