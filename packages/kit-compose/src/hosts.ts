// Screens and host apps on kit-compose (exit step "blocks, screens, hosts" of docs/ui8kit3-xgen-exit.md): every screen spec
// (packages/compose-gen/specs/screens) through the compose-gen screen emitters onto the kit-compose packages, the four host apps
// (apps/host-<runtime>: scaffold + gen/), the shared package (packages/shared/app) and the copy decks (packages/taste-data/content).
// Also the four composition packages the hosts import: packages/kit-compose/<runtime> (@codegen-x/<runtime>-compose: package.json,
// src/index.ts barrel, src/styles). `bun src/hosts.ts [--check]`.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { ROOT as GEN, portableTo, tierDir, fileName, type OrganismSpec } from "../../compose-gen";
import { APP_FILE, findApps, loadApp, sourcesOf, type AppSpec, type ScreenSpec } from "../../compose-gen/screens/src/index";
import { BANNER, HOST_GEN, SHARED, SHARED_DIR, decksFile, jsonFile, sharedPackage, type GeneratedFile } from "../../compose-gen/runtimes/core/src/index";
import * as react from "../../compose-gen/runtimes/react/src/index";
import * as svelte from "../../compose-gen/runtimes/svelte/src/index";
import * as vue from "../../compose-gen/runtimes/vue/src/index";
import * as solid from "../../compose-gen/runtimes/solid/src/index";
import { loadOrganisms, JS_RUNTIMES, type JsRuntime } from "./organisms";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const WS = path.resolve(root, "../..");
const RT = { react, svelte, vue, solid } as const;
const EXT: Record<JsRuntime, string> = { react: "tsx", svelte: "svelte", vue: "vue", solid: "tsx" };
const LABEL: Record<JsRuntime, string> = { react: "React 19", svelte: "Svelte 5", vue: "Vue 3", solid: "SolidJS 1.9" };

/** the screens a host serves: its list, or every screen portable to its runtime for ["*"] */
function hostedScreens(app: AppSpec, all: ScreenSpec[]): { screens: ScreenSpec[]; missing: string[] } {
  if (app.screens.includes("*")) return { screens: all.filter((s) => portableTo(s.portable as never, app.runtime as never) === true), missing: [] };
  const screens: ScreenSpec[] = [], missing: string[] = [];
  for (const id of app.screens) { const s = all.find((x) => x.id === id); if (s) screens.push(s); else missing.push(id); }
  return { screens, missing };
}

const css = (s: string) => `/* ${BANNER} */\n${s}`;

/** the composition package of a runtime: the API the screens import (compositions, organisms, LucideIcon, presets, utils) and the styles */
function composePackage(r: JsRuntime, organisms: OrganismSpec[]): GeneratedFile[] {
  const jsx = r === "react" || r === "solid";
  const presets = readdirSync(path.join(root, r, "src/presets")).filter((f) => f.endsWith(".ts")).sort();
  const presetNames = presets.map((f) => [f, /export const (\w+)/.exec(readFileSync(path.join(root, r, "src/presets", f), "utf8"))![1]!] as const);
  const index = [
    `// ${BANNER}`,
    `// The composition package of ${r}: the compositions over the UI8Kit 3 primitives, the organisms, the Lucide glyph and the presets.`,
    `export * from "./compose";`,
    `export * from "./organisms";`,
    jsx ? `export { LucideIcon, type LucideIconProps } from "./icons/LucideIcon";` : `export { default as LucideIcon } from "./icons/LucideIcon.${EXT[r]}";`,
    ...presetNames.map(([f, n]) => `export { ${n} } from "./presets/${f.replace(/\.ts$/, "")}";`),
    `export { cn, variants, tpl, fmtNumber, fmtMoney, at, pageWindow, fitCols, uniqLabel, urlOf, srcsetOf, cssValue } from "./utils";`,
    ``,
  ].join("\n");
  const styles = path.join(GEN, "runtimes/core/assets/styles");
  return [
    { path: "src/index.ts", contents: index },
    { path: "src/styles/theme.css", contents: readFileSync(path.join(styles, "theme.css"), "utf8") },
    { path: "src/styles/kit.css", contents: readFileSync(path.join(styles, "kit.css"), "utf8") },
    { path: "src/styles/index.css", contents: css(`/* Entry of the styles: theme tokens and the kit CSS. @source makes Tailwind v4 scan the compositions and the installed primitives. */\n@import "./theme.css";\n@import "./kit.css";\n\n@source "../";\n@source "../../../kit/${r}/src";\n`) },
    jsonFile("package.json", {
      name: `@codegen-x/${r}-compose`, version: "0.0.0", private: true, type: "module",
      description: `${LABEL[r]} compositions on the UI8Kit 3 primitives (packages/kit/${r}) and the organisms, generated by packages/kit-compose. Source only: the consumer's Vite compiles it.`,
      sideEffects: ["*.css"],
      // the zone of the rules gate (packages/tooling/rules): the organisms are the composition, a block or a frame opens on Block
      ui8kit: {
        runtime: r, generated: true, kit: ["src/compose", "src/icons", "src/presets", "src/utils", "src/styles"], composition: ["src/blocks", "src/components"],
        blockRoot: ["src/blocks", ...organisms.filter((o) => (o as { frame?: unknown }).frame && tierDir(o.id) === "components").map((o) => `src/components/${fileName(o.name)}.${EXT[r]}`).sort()],
      },
      exports: { ".": { ...(r === "svelte" ? { svelte: "./src/index.ts" } : {}), types: "./src/index.ts", default: "./src/index.ts" }, "./styles/*": "./src/styles/*", "./package.json": "./package.json" },
      dependencies: { clsx: "^2.1.1", "tailwind-merge": "^3.7.0" },
      peerDependencies: { ...{ svelte: { svelte: "^5.57.0" }, react: { react: "^19.2.0" }, vue: { vue: "^3.5.43" }, solid: { "solid-js": "^1.9.0" } }[r], tailwindcss: "^4.3.3" },
    }),
  ];
}

export interface HostTarget { dir: string; files: GeneratedFile[]; /** folders the generator owns whole: cleared on write */ owned: string[]; keep?: RegExp }

export function hostTargets(): { targets: HostTarget[]; problems: string[] } {
  const loaded = loadOrganisms();
  const { parts, inputs } = loaded;
  const problems: string[] = [];
  const orgs = Object.fromEntries(inputs.organisms.map((o) => [o.value.name, o.value as OrganismSpec]));
  const all = inputs.screens.map((s) => s.value as ScreenSpec);
  const targets: HostTarget[] = JS_RUNTIMES.map((r) => ({ dir: `packages/kit-compose/${r}`, files: composePackage(r, Object.values(orgs)), owned: [] }));
  const hosted = new Map<string, ScreenSpec>();
  for (const dir of findApps(WS)) {
    const { app, problems: p } = loadApp(path.join(dir, APP_FILE));
    problems.push(...p);
    const r = app.runtime as JsRuntime;
    if (!JS_RUNTIMES.includes(r)) { problems.push(`${dir}: runtime ${app.runtime} has no host`); continue; }
    const { screens, missing } = hostedScreens(app, all);
    for (const id of missing) problems.push(`${path.basename(dir)}: screen ${id} does not exist`);
    for (const s of screens) hosted.set(s.id, s);
    const files: GeneratedFile[] = [...RT[r].appScaffold(app as never, screens as never)];
    for (const s of screens) {
      const deps = { parts, organisms: orgs, partPath: () => "", ui: RT[r].UI, shared: SHARED, recordType: s.source?.record ?? "" };
      try {
        for (const c of [RT[r].emitScreen(s as never, deps as never), ...RT[r].emitChunks(s as never, deps as never)]) files.push({ path: `${HOST_GEN}/${c.path}`, contents: c.contents });
      } catch (e) { problems.push(`${path.basename(dir)} ${s.id}: ${(e as Error).message}`); }
    }
    targets.push({ dir: path.relative(WS, dir), files, owned: [HOST_GEN] });
  }
  // what every host reads, emitted once: the dictionary, the fixtures of the hosted screens and their lookups, menus, registry, url core
  const shared = [...hosted.values()].sort((a, b) => a.id.localeCompare(b.id));
  const cols = new Set(shared.flatMap((s) => sourcesOf(s).map((x) => x.collection)));
  const LOOKUP_KINDS = ["media", "user"];
  const picked = inputs.collections.map((c) => c.value).filter((c) => cols.has(c.collection) || c.entries.every((e) => LOOKUP_KINDS.includes(e.kind)) && c.entries.length > 0);
  const pickedIds = new Set(picked.flatMap((c) => c.entries.map((e) => e.id)));
  const collections = inputs.collections.map((c) => c.value).filter((c) => picked.includes(c) || c.entries.length > 0 && c.entries.every((e) => e.kind === "menu_item" && pickedIds.has((e as { parent_id?: string }).parent_id ?? "")));
  targets.push({ dir: SHARED_DIR, // src/runtime/skin-fonts.ts belongs to the skins generator (bun run skins build): kept, not written here
    files: sharedPackage(inputs.dictionary.value, collections, shared, inputs.taxonomies.map((t) => t.value)).filter((f) => !SKINS_OWNED.test(f.path)), owned: ["src"], keep: SKINS_OWNED });
  targets.push({ dir: "packages/taste-data/content", files: [decksFile(inputs.collections.map((c) => c.value))], owned: [] });
  return { targets, problems };
}

const SKINS_OWNED = /^src\/runtime\/skin-fonts\.ts$/;

function walk(dir: string, rel = ""): string[] {
  if (!existsSync(path.join(dir, rel))) return [];
  return readdirSync(path.join(dir, rel), { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(dir, path.join(rel, e.name)) : [path.join(rel, e.name)]));
}

if (import.meta.main) {
  const check = process.argv.includes("--check"), bad: string[] = [];
  const { targets, problems } = hostTargets();
  if (problems.length) { console.error(`hosts:\n${problems.join("\n")}`); process.exit(1); }
  let n = 0;
  for (const t of targets) {
    const base = path.join(WS, t.dir);
    const want = new Map(t.files.map((f) => [f.path, f.contents]));
    n += want.size;
    if (check) {
      for (const [rel, body] of want) { const p = path.join(base, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(path.join(t.dir, rel)); }
      for (const o of t.owned) for (const f of walk(path.join(base, o))) if (!want.has(path.join(o, f)) && !t.keep?.test(path.join(o, f))) bad.push(`${path.join(t.dir, o, f)} (stale)`);
    } else {
      for (const o of t.owned) for (const f of walk(path.join(base, o))) if (!want.has(path.join(o, f)) && !t.keep?.test(path.join(o, f))) rmSync(path.join(base, o, f));
      for (const [rel, body] of want) { const p = path.join(base, rel); mkdirSync(path.dirname(p), { recursive: true }); writeFileSync(p, body); }
    }
  }
  console.log(`hosts: ${targets.length} targets, ${n} files${check ? "" : " written"}`);
  if (bad.length) { console.error(`hosts out of date (bun packages/kit-compose/src/hosts.ts):\n${bad.slice(0, 30).join("\n")}`); process.exit(1); }
}
