// Thin build: src/map.ts + variants/*.variants.json -> <runtime>/src/compose/* (compositions over packages/kit/<runtime>).
// Every composition = one v3 primitive + a fixed tag + cn(recipe classes, extra, caller class). No logic of its own.
// bun src/build.ts [--check]   (--check fails on any difference from the disk)
import { mkdirSync, readFileSync, writeFileSync, existsSync, readdirSync, rmSync, symlinkSync, readlinkSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { BRICKS, type BrickMap } from "./map";
import { RECIPES } from "./recipes";
import { serverFiles, SERVER_RT } from "./server";
import { manualFiles, MANUAL } from "./manual";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const HEAD = "Code generated by packages/kit-compose/src/build.ts from src/map.ts + variants/. DO NOT EDIT.";
const VOID = new Set(["Input", "Checkbox", "Radio", "Switch", "Separator", "Image"]);
const DIR: Record<string, string> = { Summary: "disclosure", SelectOption: "select", SelectOptGroup: "select" };
const dirOf = (p: string) => DIR[p] ?? p.toLowerCase();
const kebab = (s: string) => s.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();
const JS_RT = ["react", "svelte", "vue", "solid"] as const;
const RT = [...JS_RT, ...SERVER_RT] as const;
const KIT = path.resolve(root, "../kit");
/** kitmod/ui, kitmod/utils -> the installed templ kit (go module root for the compositions) */
const LINKS: [string, string][] = [["templ/kitmod/ui", "../../../kit/templ/src/ui"], ["templ/kitmod/utils", "../../../kit/templ/src/utils"]];

// every brick, also a bare one (SelectOption, OptGroup: the primitive, no classes) in the JS runtimes, where the organisms import
// all bricks from ../compose; the server templates include the primitive itself (Option/OptGroup props there have no Class)
const items = Object.entries(BRICKS) as [string, BrickMap][];
const styled = items.filter(([, m]) => m.recipe || m.extra || m.tag || m.tagFrom);

function recipesTs(): string {
  const used = [...new Set([...items.map(([, m]) => m.recipe), "themetoggle", "sheettrigger"].filter(Boolean))] as string[];
  const data = Object.fromEntries(used.sort().map((id) => {
    const { base, keys, defaults, byKey, compound } = RECIPES[id];
    return [id, { base, keys, defaults, byKey, compound: compound ?? [] }];
  }));
  return `// ${HEAD}
// Token-only recipes of the compositions (source: packages/kit-compose/variants).
type R = { base: string; keys: string[]; defaults: Record<string, string>; byKey: Record<string, Record<string, string>>; compound: Array<Record<string, string>> };
export const RECIPES: Record<string, R> = ${JSON.stringify(data, null, 2)};

/** Classes of recipe \`id\` for the given values (unset = defaults), compound variants included. */
export function rc(id: string, values: Record<string, string | number | undefined>): string {
  const r = RECIPES[id];
  const pick = (k: string) => (values[k] === undefined || values[k] === "" ? r.defaults[k] : String(values[k]));
  const out = [r.base, ...r.keys.map((k) => r.byKey[k]?.[pick(k) ?? ""] ?? "")];
  for (const c of r.compound) {
    const { class: cls, ...when } = c;
    if (Object.entries(when).every(([k, v]) => pick(k) === v)) out.push(cls);
  }
  return out.filter(Boolean).join(" ");
}
`;
}

const keysOf = (m: BrickMap) => (m.recipe ? RECIPES[m.recipe].keys : []);
const tagExpr = (m: BrickMap, v: string) =>
  m.tagFrom?.heading ? `(${v} && Number(${v}) >= 1 && Number(${v}) <= 6 ? \`h\${${v}}\` : "${m.tagFrom.fallback}")`
  : m.tagFrom ? `(${v} ?? "${m.tagFrom.fallback}")` : JSON.stringify(m.tag);
const tagProp = (m: BrickMap) => (m.tagFrom ? (m.tagFrom.heading ? "as" : "tag") : undefined);
const clsExpr = (m: BrickMap, user: string) =>
  `cn(${[m.recipe ? `rc("${m.recipe}", { ${keysOf(m).map((k) => `${JSON.stringify(k)}: ${safe(k)}`).join(", ")} })` : "", m.extra ? JSON.stringify(m.extra) : "", user].filter(Boolean).join(", ")})`;
const safe = (k: string) => `v_${k.replace(/[^a-z0-9]/gi, "_")}`;
/** the trail element, rendered by the kit Text primitive (the gates allow no raw html): jsx (className) or class */
const trailOf = (m: BrickMap, jsx: string | null): string => !m.trail ? "" : `<Text tag="${m.trail.tag}"${Object.entries(m.trail.attrs).map(([k, v]) => ` ${k === "class" && jsx ? jsx : k}=${JSON.stringify(v)}`).join("")} />`;
const trailImport = (m: BrickMap, rt: string): string => !m.trail ? "" : rt === "react" ? `import { Text } from "../../../../kit/react/src/ui/text/text";\n`
  : rt === "solid" ? `import { Text } from "../../../../kit/solid/src/ui/text/text.solid";\n` : `${rt === "svelte" ? "  " : ""}import Text from "../../../../kit/${rt}/src/ui/text/Text.${rt}";\n`;
const fixedAttrs = (m: BrickMap) => Object.entries(m.fixed ?? {});
/** the implied ARIA attribute, placed before the caller's rest (the caller wins): ref = how the runtime reads the recipe key */
const impliedAttr = (m: BrickMap, ref: (k: string) => string, vue = false): string => !m.implies ? ""
  : vue ? ` :${m.implies.attr}="${ref(m.implies.key)} === '${m.implies.value}' ? '${m.implies.set}' : undefined"`
  : ` ${m.implies.attr}={${ref(m.implies.key)} === ${JSON.stringify(m.implies.value)} ? ${JSON.stringify(m.implies.set)} : undefined}`;

function react(name: string, m: BrickMap): string {
  const p = m.primitive, tp = tagProp(m), keys = keysOf(m);
  const destr = [...keys.map((k) => `${JSON.stringify(k)}: ${safe(k)}`), ...(tp ? [tp] : []), "className", ...(m.trail ? ["children"] : []), "...rest"].join(", ");
  const own = [...keys.map((k) => `${JSON.stringify(k)}?: string | number`), ...(tp ? [`${tp}?: ${tp === "as" ? "number | string" : "string"}`] : []),
    ...Object.entries(m.attrs ?? {}).map(([k, t]) => `${k}?: ${t}`)].join("; ");
  const tag = m.tag || m.tagFrom ? ` tag={${tagExpr(m, tp ?? "undefined")} as never}` : "";
  return `// ${HEAD}
import type { ComponentProps } from "react";
import { ${p} as Prim } from "../../../../kit/react/src/ui/${dirOf(p)}/${dirOf(p)}";
${trailImport(m, "react")}import { cn } from "../../../../kit/react/src/utils";
import { rc } from "./recipes";

export type ${name}Props = Omit<ComponentProps<typeof Prim>, ${["tag", ...keys].map((k) => JSON.stringify(k)).join(" | ")}> & { ${own}${own ? "; " : ""}className?: string };

/** ${name}: ${p}${m.tag ? ` <${m.tag}>` : ""}${m.recipe ? ` + recipe ${m.recipe}` : ""}. */
export function ${name}({ ${destr} }: ${name}Props) {
  return <Prim${tag} className={${clsExpr(m, "className")}}${fixedAttrs(m).map(([k, v]) => ` ${k}=${JSON.stringify(v)}`).join("")}${impliedAttr(m, safe)} {...rest}${m.trail ? `>{children}${trailOf(m, "className")}</Prim>` : " />"};
}
`;
}

/** the primitive props without the tag the composition retypes (string); Omit only when needed: it drops required props behind an index signature */
const svelteBase = (m: BrickMap, _keys: string[]): string => {
  const omit = m.tag || m.tagFrom ? ["tag"] : [];
  return omit.length ? `Omit<ComponentProps<typeof Prim>, ${omit.map((k) => JSON.stringify(k)).join(" | ")}>` : "ComponentProps<typeof Prim>";
};

function svelte(name: string, m: BrickMap): string {
  const p = m.primitive, tp = tagProp(m), keys = keysOf(m);
  const destr = [...keys.map((k) => `${JSON.stringify(k)}: ${safe(k)}`), ...(tp ? [tp] : []), "class: className", "children", "...rest"].join(", ");
  const tag = m.tag || m.tagFrom ? ` tag={${tagExpr(m, tp ?? "undefined")} as never}` : "";
  const open = `<Prim${tag} class={cls}${fixedAttrs(m).map(([k, v]) => ` ${k}=${JSON.stringify(v)}`).join("")}${impliedAttr(m, safe)} {...rest}`;
  return `<!-- ${HEAD} -->
<!-- ${name}: ${p}${m.tag ? ` <${m.tag}>` : ""}${m.recipe ? ` + recipe ${m.recipe}` : ""}. -->
<script lang="ts">
  import type { ComponentProps, Snippet } from "svelte";
  import Prim from "../../../../kit/svelte/src/ui/${dirOf(p)}/${p}.svelte";
${trailImport(m, "svelte")}  import { cn } from "../../../../kit/svelte/src/utils";
  import { rc } from "./recipes";

  let { ${destr} }: ${svelteBase(m, keys)} & { ${[...keys.map((k) => `${JSON.stringify(k)}?: string | number`), ...(tp ? [`${tp}?: string | number`] : []), ...Object.entries(m.attrs ?? {}).map(([k, t]) => `${k.toLowerCase()}?: ${t}`), "class?: string", "children?: Snippet"].join("; ")} } = $props();
  const cls = $derived(${clsExpr(m, "className")});
</script>

${VOID.has(p) ? `${open} />` : `${open}>{@render children?.()}${trailOf(m, null)}</Prim>`}
`;
}

function vue(name: string, m: BrickMap): string {
  const p = m.primitive, tp = tagProp(m), keys = keysOf(m);
  const req = m.required ?? [];
  const propsT = [...keys.map((k) => `${JSON.stringify(k)}?: string | number`), ...(tp ? [`${tp}?: string | number`] : []), ...req.map((k) => `${k}: string`)].join("; ");
  const ref = (k: string) => `props[${JSON.stringify(k)}]`;
  const cls = `cn(${[m.recipe ? `rc("${m.recipe}", { ${keys.map((k) => `${JSON.stringify(k)}: ${ref(k)}`).join(", ")} })` : "", m.extra ? JSON.stringify(m.extra) : "", "attrs.class as string | undefined"].filter(Boolean).join(", ")})`;
  const tag = m.tag || m.tagFrom ? ` :tag="tagValue as never"` : "";
  const tagJs = m.tagFrom?.heading ? `(props.as && Number(props.as) >= 1 && Number(props.as) <= 6 ? \`h\${props.as}\` : "${m.tagFrom.fallback}")`
    : m.tagFrom ? `(props.tag ?? "${m.tagFrom.fallback}")` : JSON.stringify(m.tag ?? "");
  const open = `<Prim${tag}${req.map((k) => ` :${k}="props.${k}"`).join("")} :class="cls"${fixedAttrs(m).map(([k, v]) => ` ${k}=${JSON.stringify(v)}`).join("")}${impliedAttr(m, (k) => `props.${k}`, true)} v-bind="rest"`;
  return `<!-- ${HEAD} -->
<!-- ${name}: ${p}${m.tag ? ` <${m.tag}>` : ""}${m.recipe ? ` + recipe ${m.recipe}` : ""}. -->
<script setup lang="ts">
import { computed, useAttrs } from "vue";
import Prim from "../../../../kit/vue/src/ui/${dirOf(p)}/${p}.vue";
${trailImport(m, "vue")}import { cn } from "../../../../kit/vue/src/utils";
import { rc } from "./recipes";

defineOptions({ name: "${name}", inheritAttrs: false });
const props = defineProps<{ ${propsT} }>();
const attrs = useAttrs();
const rest = computed(() => {
  const { class: _class, ...r } = attrs;
  return r;
});
const cls = computed(() => ${cls});
const tagValue = computed(() => ${tagJs});
</script>

<template>
  ${VOID.has(p) ? `${open} />` : `${open}><slot />${trailOf(m, null)}</Prim>`}
</template>
`;
}

function solid(name: string, m: BrickMap): string {
  const p = m.primitive, tp = tagProp(m), keys = keysOf(m);
  const own = [...keys.map((k) => `${JSON.stringify(k)}?: string | number`), ...(tp ? [`${tp}?: ${tp === "as" ? "number | string" : "string"}`] : []),
    ...Object.entries(m.attrs ?? {}).map(([k, t]) => `${k}?: ${t}`), "class?: string", "className?: string"].join("; ");
  const L = (k: string) => `local[${JSON.stringify(k)}]`;
  const cls = `cn(${[m.recipe ? `rc("${m.recipe}", { ${keys.map((k) => `${JSON.stringify(k)}: ${L(k)}`).join(", ")} })` : "", m.extra ? JSON.stringify(m.extra) : "", "local.class ?? local.className"].filter(Boolean).join(", ")})`;
  const tagJs = m.tagFrom?.heading ? `(local.as && Number(local.as) >= 1 && Number(local.as) <= 6 ? \`h\${local.as}\` : "${m.tagFrom.fallback}")`
    : m.tagFrom ? `(local.tag ?? "${m.tagFrom.fallback}")` : JSON.stringify(m.tag ?? "");
  const tag = m.tag || m.tagFrom ? ` tag={${tagJs} as never}` : "";
  return `// ${HEAD}
import { splitProps, type ComponentProps } from "solid-js";
import { ${p} as Prim } from "../../../../kit/solid/src/ui/${dirOf(p)}/${dirOf(p)}.solid";
${trailImport(m, "solid")}import { cn } from "../../../../kit/solid/src/utils";
import { rc } from "./recipes";

export type ${name}Props = Omit<ComponentProps<typeof Prim>, ${["tag", "class", "className", ...keys].map((k) => JSON.stringify(k)).join(" | ")}> & { ${own} };

/** ${name}: ${p}${m.tag ? ` <${m.tag}>` : ""}${m.recipe ? ` + recipe ${m.recipe}` : ""}. */
export function ${name}(props: ${name}Props) {
  const [local, rest] = splitProps(props, [${[...keys, ...(tp ? [tp] : []), "class", "className", ...(m.trail ? ["children"] : [])].map((k) => JSON.stringify(k)).join(", ")}]);
  return <Prim${tag} class={${cls}}${fixedAttrs(m).map(([k, v]) => ` ${k}=${JSON.stringify(v)}`).join("")}${impliedAttr(m, L)} {...rest}${m.trail ? `>{local.children}${trailOf(m, null)}</Prim>` : " />"};
}
`;
}

function plan(): Map<string, string> {
  const files = new Map<string, string>();
  for (const [k, v] of serverFiles(styled, KIT, HEAD)) files.set(k, v);
  for (const [k, v] of manualFiles(HEAD)) files.set(k, v);
  for (const rt of JS_RT) {
    const dir = `${rt}/src/compose`;
    files.set(`${dir}/recipes.ts`, recipesTs());
    const index: string[] = [`// ${HEAD}`];
    for (const [name, m] of items) {
      if (rt === "react") { files.set(`${dir}/${kebab(name)}.tsx`, react(name, m)); index.push(`export * from "./${kebab(name)}";`); }
      else if (rt === "solid") { files.set(`${dir}/${kebab(name)}.solid.tsx`, solid(name, m)); index.push(`export * from "./${kebab(name)}.solid";`); }
      else if (rt === "vue") { files.set(`${dir}/${name}.vue`, vue(name, m)); index.push(`export { default as ${name} } from "./${name}.vue";`); }
      else { files.set(`${dir}/${name}.svelte`, svelte(name, m)); index.push(`export { default as ${name} } from "./${name}.svelte";`); }
    }
    for (const name of MANUAL) index.push(rt === "react" ? `export * from "./${kebab(name)}";` : rt === "solid" ? `export * from "./${kebab(name)}.solid";` : `export { default as ${name} } from "./${name}.${rt}";`);
    index.push(`export { rc, RECIPES } from "./recipes";`);
    files.set(`${dir}/index.ts`, index.join("\n") + "\n");
  }
  return files;
}

const files = plan();
if (process.argv.includes("--check")) {
  const bad: string[] = [];
  for (const [rel, body] of files) { const p = path.join(root, rel); if (!existsSync(p) || readFileSync(p, "utf8") !== body) bad.push(rel); }
  for (const rt of RT) { const d = path.join(root, rt, "src/compose"); if (existsSync(d)) for (const f of readdirSync(d)) if (f !== "__pycache__" && !files.has(`${rt}/src/compose/${f}`)) bad.push(`${rt}/src/compose/${f} (stale)`); }
  for (const [l, t] of LINKS) { let cur = ""; try { cur = readlinkSync(path.join(root, l)); } catch {} if (cur !== t) bad.push(`${l} (symlink -> ${t})`); }
  if (bad.length) { console.error(`kit-compose: out of date (bun run --cwd packages/kit-compose build):\n  ${bad.join("\n  ")}`); process.exit(1); }
  console.log(`kit-compose: ${items.length} compositions x ${RT.length} runtimes up to date`);
} else {
  for (const rt of RT) rmSync(path.join(root, rt, "src/compose"), { recursive: true, force: true });
  for (const [rel, body] of files) { mkdirSync(path.dirname(path.join(root, rel)), { recursive: true }); writeFileSync(path.join(root, rel), body); }
  for (const [l, t] of LINKS) { rmSync(path.join(root, l), { force: true }); symlinkSync(t, path.join(root, l)); }
  console.log(`kit-compose: wrote ${files.size} files (${items.length} compositions x ${RT.length} runtimes)`);
}
